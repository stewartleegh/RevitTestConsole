using NUnit.Framework;

namespace SampleCommand.Tests
{
	/// <summary>
	/// 普通单元测试示例：纯托管逻辑，不触碰 RevitAPI，
	/// 在 --no-revit 模式、Revit 进程内运行器下均可执行。
	/// 注意：内置 LightweightTestRunner 仅识别 [TestFixture]/[Test]，
	/// 不支持 [TestCase] 参数化用例，请编写普通 [Test] 方法并通过局部变量组织数据。
	/// </summary>
	[TestFixture]
	public class SampleCommandTests
	{
		[Test]
		public void Sum_TwoPositiveNumbers_ReturnsExpectedResult()
		{
			int result = Add(2, 3);

			Assert.That(result, Is.EqualTo(5));
		}

		[Test]
		public void Sum_WithNegativeNumber_HandlesSignCorrectly()
		{
			int result = Add(10, -4);

			Assert.That(result, Is.EqualTo(6));
		}

		[Test]
		public void FormatReportHeader_AlwaysContainsConsoleName()
		{
			string header = FormatReportHeader("SampleCommand");

			Assert.That(header, Does.Contain("Revit Test Console"));
			Assert.That(header, Does.Contain("SampleCommand"));
		}

		// ---- 以下为被测的纯托管辅助逻辑（示例项目自带，用于演示普通单元测试的写法） ----

		private static int Add(int left, int right)
		{
			return left + right;
		}

		private static string FormatReportHeader(string commandName)
		{
			return string.Format("[{0}] report generated by Revit Test Console", commandName);
		}
	}
}
